-- Описание формы: текст над полями.
--
-- ⚠️ ЗАЧЕМ ОТДЕЛЬНОЕ ПОЛЕ, а не первый абзац в названии. У формы бывает
-- вводный текст: даты, правила, куда писать с вопросами. Владелец вписывает
-- его ОДИН раз в конструкторе, и оно показывается на публичной странице
-- между заголовком и полями.
--
-- ⚠️ Почему это не «поле формы» (forms.Fields): поле ввода имеет значение
-- ответа и попадает в `field_fills`. Описание — статический текст, ответа
-- не имеет. Если сделать его полем, оно попало бы в выгрузки и аналитику
-- как «вопрос без ответа».
--
-- ⚠️ TEXT, а не varchar: правила бывают длинными (даты, условия, ссылки),
-- и обрезать по 255 — источник будущих правок.
ALTER TABLE forms ADD COLUMN IF NOT EXISTS description text NOT NULL DEFAULT '';
